    #[test]
    fn folds_a_same_line_weakness_bonus_into_total_damage() {
        // "...used Lightning Rondo on Shinwrld's Radiant Greninja for 340
        // damage. Shinwrld's Radiant Greninja took 170 more damage because
        // of Lightning Weakness." — two sentences on one line. The old
        // regex (no `$` anchor) silently truncated at 340, dropping the
        // real total (510) HP math needs.
        let log = parse(FULL);
        let attack = log
            .turns
            .iter()
            .flat_map(|t| &t.events)
            .find(|e| matches!(&e.kind, EventKind::Attack { move_name, .. } if move_name == "Lightning Rondo" && matches!(&e.kind, EventKind::Attack { target_pokemon: Some(p), .. } if p == "Radiant Greninja")));
        let Some(TurnEvent { kind: EventKind::Attack { damage, damage_modifier, .. }, .. }) = attack else {
            panic!("expected the Lightning Rondo vs. Radiant Greninja attack");
        };
        assert_eq!(*damage, Some(510));
        assert_eq!(*damage_modifier, Some(170));
    }

    #[test]
    fn possessive_named_cards_dont_leak_into_the_owner() {
        // "Trainer's Pokémon" cards ("Marnie's Grimmsnarl", "Ethan's Ho-Oh
        // ex") carry their own possessive. The `'s`-owner patterns must not
        // greedily read that as part of the player name, or the event lands
        // on a phantom player and board reconstruction silently drops it
        // (e.g. an Active-swap that never appears to happen).
        match classify_top_level("reindoe12's Marnie's Grimmsnarl is now in the Active Spot.") {
            EventKind::NowActive { player, pokemon } => {
                assert_eq!(player, "reindoe12");
                assert_eq!(pokemon, "Marnie's Grimmsnarl");
            }
            other => panic!("expected NowActive, got {other:?}"),
        }
        match classify_top_level("reindoe12's Marnie's Grimmsnarl was Knocked Out!") {
            EventKind::KnockedOut { player, pokemon } => {
                assert_eq!(player, "reindoe12");
                assert_eq!(pokemon, "Marnie's Grimmsnarl");
            }
            other => panic!("expected KnockedOut, got {other:?}"),
        }
        match classify_top_level(
            "Guibattis28's Marnie's Grimmsnarl used Moxie Punch on reindoe12's Munkidori for 120 damage.",
        ) {
            EventKind::Attack { player, pokemon, target_player, target_pokemon, damage, .. } => {
                assert_eq!(player, "Guibattis28");
                assert_eq!(pokemon, "Marnie's Grimmsnarl");
                assert_eq!(target_player.as_deref(), Some("reindoe12"));
                assert_eq!(target_pokemon.as_deref(), Some("Munkidori"));
                assert_eq!(damage, Some(120));
            }
            other => panic!("expected Attack, got {other:?}"),
        }
    }

